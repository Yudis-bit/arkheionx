def render_review_map_summary(rm: ReviewMap) -> str:
    s = rm.summary
    out = [
        "# Review Map Summary",
        "",
        "> Local/static heuristic review surface. Review guidance only, not findings.",
        "",
        f"- Repository: `{rm.repo_path}`",
        f"- Mode: {rm.mode} (heuristic)",
        f"- Protocol types: {', '.join(s.protocol_types) or 'generic'}",
        f"- Contracts: {s.contracts_analyzed} · Functions: {s.functions_mapped}",
        f"- Value paths: {s.value_paths} · Assumptions: {s.assumptions} · Test gaps: {s.test_gaps}",
        "",
        "## Inspect-first surfaces (review order, not severity)",
        "",
    ]
    notes = rm.reviewer_notes[:8]
    if notes:
        for n in notes:
            out.append(f"- `{n.title}` — {n.body}")
    else:
        out.append("_No inspect-first reviewer notes surfaced._")
    out += ["", "## Value paths", ""]
    if rm.value_paths:
        for vp in rm.value_paths[:10]:
            out.append(f"- `{vp.id}` — {vp.label} (coverage hint: {vp.test_coverage_hint})")
    else:
        out.append("_No value paths surfaced._")
    out += ["", "## Assumptions (unverified guarding properties)", ""]
    if rm.assumptions:
        for a in rm.assumptions:
            out.append(f"- `{a.id}` [{a.category}] {a.title} — used by: {', '.join(a.used_by) or '—'}")
    else:
        out.append("_No assumptions surfaced._")
    out += ["", "## Test gaps", ""]
    if rm.test_gaps:
        for g in rm.test_gaps[:12]:
            out.append(f"- `{g.id}` {g.related_function} — {g.rationale or g.title}")
    else:
        out.append("_No test gaps surfaced._")
    out += ["", "---", "", rm.safety.disclaimer, ""]
    return "\n".join(out) + "\n"



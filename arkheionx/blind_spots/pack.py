# Files are written in this fixed order so the manifest artifact list is stable.
_MARKDOWN_FILES = (
    "00-README.md", "01-review-map-summary.md", "02-blind-spots.md", "03-criticality-map.md",
    "04-counterfactuals.md", "05-agent-brief.md", "06-hypotheses.md", "07-evidence-log.md",
    "08-do-not-claim.md", "09-case-study-template.md",
)
_JSON_FILES = (
    "blind-spots.json", "criticality-map.json", "counterfactuals.json",
    "agent-brief.json", "hypotheses.json", "case-study.json", "manifest.json",
)

COMMANDS_REPRESENTED = ["review-map", "blind-spots", "criticality-map", "counterfactuals",
                        "agent-brief", "hypothesis-log", "case-study"]


def build_research_pack(rm: ReviewMap, root, out_dir, *, package_version: str,
                        source_files: int = 0, test_files: int = 0, write: bool = True) -> dict:
    """Build all pack payloads, write every file (unless ``write`` is False), and
    return the manifest + paths. When ``write`` is False no files are written and
    ``written`` maps each artifact to its intended (unwritten) path."""
    out_dir = Path(out_dir)

    blind_spots = build_blind_spot_map_from_review_map(rm, root, source_files=source_files, test_files=test_files)
    criticality = build_criticality_map_from_review_map(rm, root, source_files=source_files, test_files=test_files)
    counterfactuals = build_counterfactual_plan_from_review_map(rm, root, source_files=source_files, test_files=test_files)
    agent_brief = build_agent_brief_from_review_map(rm, root, source_files=source_files, test_files=test_files)
    hypotheses = build_hypothesis_log_from_review_map(rm, root)
    case_study = build_case_study_from_review_map(rm, root)

    contents = {
        "00-README.md": render_pack_readme(rm, package_version),
        "01-review-map-summary.md": render_review_map_summary(rm),
        "02-blind-spots.md": render.render_blind_spots_md(blind_spots),
        "03-criticality-map.md": render.render_criticality_map_md(criticality),
        "04-counterfactuals.md": render.render_counterfactuals_md(counterfactuals),
        "05-agent-brief.md": render_agent_brief_md(agent_brief),
        "06-hypotheses.md": render_hypothesis_log_md(hypotheses),
        "07-evidence-log.md": render_evidence_log_template(),
        "08-do-not-claim.md": render_do_not_claim(),
        "09-case-study-template.md": render_case_study_md(case_study),
    }
    json_payloads = {
        "blind-spots.json": blind_spots,
        "criticality-map.json": criticality,
        "counterfactuals.json": counterfactuals,
        "agent-brief.json": agent_brief,
        "hypotheses.json": hypotheses,
        "case-study.json": case_study,
    }

    written: dict[str, str] = {}
    for name in _MARKDOWN_FILES:
        written[name] = _write(out_dir / name, contents[name]) if write else str(out_dir / name)
    for name, payload in json_payloads.items():
        written[name] = _write(out_dir / name, json.dumps(payload, indent=2)) if write else str(out_dir / name)

    manifest = {
        "schema_version": m.SCHEMA_VERSION,
        "kind": m.KIND_RESEARCH_PACK_MANIFEST,
        "generated_at": rm.generated_at,
        "repo_path": rm.repo_path,
        "mode": rm.mode,
        "package_version": package_version,
        "commands_represented": list(COMMANDS_REPRESENTED),
        "artifacts": list(_MARKDOWN_FILES) + list(_JSON_FILES),
        "counts": {
            "blind_spot_candidates": len(blind_spots["candidates"]),
            "unknown_surfaces": len(blind_spots["unknown_surfaces"]),
            "criticality_surfaces": len(criticality["surfaces"]),
            "counterfactuals": len(counterfactuals["counterfactuals"]),
            "hypotheses": len(hypotheses["hypotheses"]),
        },
        "safety": {
            "local_static_only": True,
            "no_rpc": True,
            "no_live_chain": True,
            "no_secrets": True,
            "no_exploit_automation": True,
            "no_auto_submit": True,
            "no_severity": True,
            "no_vulnerability_claims": True,
            "vendor_agnostic": True,
            "human_review_required": True,
            "disclaimer": rm.safety.disclaimer,
        },
    }
    written["manifest.json"] = (
        _write(out_dir / "manifest.json", json.dumps(manifest, indent=2))
        if write else str(out_dir / "manifest.json"))

    return {"manifest": manifest, "written": written, "out_dir": str(out_dir)}

"""Research pack generator for the v5 Blind Spot Intelligence layer (headline).

Builds a complete, local, vendor-agnostic bug bounty research pack under one
folder. It composes the v5 blind-spot / criticality / counterfactual engine with
the v4.1 research-memory renderers (agent brief, hypotheses, case study) and adds
a README, a review-map summary, an evidence-log template, and a do-not-claim
file plus a JSON manifest.

The pack is model-agnostic and vendor-agnostic on purpose: it speaks of an "AI
agent", "review agent", "human reviewer", "researcher", and "local test runner",
never a specific product. It is local/static and makes no vulnerability claims.
"""

"""Complete Review package generator for the v6 Evidence Graph layer (headline).

Builds a complete, local, vendor-agnostic review package under one folder. It
composes the v4 review map, the v5 blind-spot / criticality / counterfactual
engine, and the v6 evidence graph, interaction matrix, and unresolved map, then
adds a README, a model-agnostic agent input, a human review checklist, and a
JSON manifest.

The pack is model-agnostic on purpose: it speaks of an "AI agent", "review
agent", "human reviewer", and "local test runner", never a specific vendor. It
is local/static and makes no vulnerability claims. Human review is required.
"""

def _write(path: Path, content: str) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not content.endswith("\n"):
        content += "\n"
    path.write_text(content, encoding="utf-8")
    return str(path)


_MARKDOWN_FILES = (
    "00-README.md", "01-review-map-summary.md", "02-blind-spots-summary.md",
    "03-criticality-summary.md", "04-counterfactuals-summary.md", "05-evidence-graph.md",
    "06-interaction-matrix.md", "07-unresolved-surfaces.md", "08-agent-input.md",
    "09-human-review-checklist.md", "10-case-study-template.md",
)
_JSON_FILES = (
    "evidence-graph.json", "interaction-matrix.json", "unresolved-map.json",
    "complete-review.json", "manifest.json",
)
COMMANDS_REPRESENTED = ["review-map", "blind-spots", "criticality-map", "counterfactuals",
                        "evidence-graph", "interaction-matrix", "unresolved-map", "complete-review"]


